"""KITTI-style evaluation with difficulty stratification.

Implements the KITTI 11-point interpolated AP metric with configurable
difficulty levels (Easy / Moderate / Hard / Overall) based on ground-
truth bounding-box height percentiles.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np


@dataclass(frozen=True)
class AttributeDifficultyConfig:
    """Config for adding per-box attribute filters into difficulty evaluation.

    Sidecar CSVs are generated by
    ``fish_monitoring/data_utils/label_attributes_txt.py``.

    We keep it flexible: if a CSV is missing or a box isn't found in it, that box
    is treated as having 'unknown' attribute and is excluded only if the selected
    difficulty explicitly requires a known value.
    """

    attributes_dir: Path | None = None
    # file naming convention: visibility_<split>.csv, background_<split>.csv
    visibility_csv: Path | None = None
    background_csv: Path | None = None

    # What counts as "hard" (low visibility)
    hard_visibility: tuple[str, ...] = ("poor",)
    # What counts as "hard" background
    hard_background: tuple[str, ...] = ("coral",)

    def resolve(self, *, dataset_dir: Path, split: str) -> "AttributeDifficultyConfig":
        attr_dir = self.attributes_dir
        if attr_dir is None:
            attr_dir = dataset_dir / "attributes"

        vis = self.visibility_csv
        bg = self.background_csv

        if vis is None:
            vis = attr_dir / f"visibility_{split}.csv"
        if bg is None:
            bg = attr_dir / f"background_{split}.csv"

        return AttributeDifficultyConfig(
            attributes_dir=attr_dir,
            visibility_csv=vis,
            background_csv=bg,
            hard_visibility=tuple(self.hard_visibility),
            hard_background=tuple(self.hard_background),
        )


@dataclass(frozen=True)
class BoxSet:
    xyxy: np.ndarray  # (N,4) float32, absolute pixels
    cls: np.ndarray  # (N,) int64
    conf: np.ndarray | None = None  # (N,) float32


@dataclass(frozen=True)
class PointMetrics:
    tp: int
    fp: int
    fn: int
    precision: float
    recall: float


@dataclass(frozen=True)
class ClassPrCurve:
    cls_id: int
    n_gt: int
    ap_11: float
    ap_continuous: float
    scores: np.ndarray  # (K,) confidence of each point (descending)
    precision: np.ndarray  # (K,)
    recall: np.ndarray  # (K,)


@dataclass(frozen=True)
class DifficultyResult:
    name: str
    min_height_px: int
    iou_th: float
    point: PointMetrics
    per_class: dict[int, PointMetrics]
    pr_curves: dict[int, ClassPrCurve]
    map_11: float
    map_continuous: float
    # (optional) attribute difficulty info
    size_pct: float | None = None
    visibility_pct: float | None = None
    background_pct: float | None = None


def _try_load_attr_csv(path: Path, *, label_col: str) -> dict[tuple[str, int], str]:
    """Load a bbox-attribute CSV into {(stem, box_index): label}.

    Expected columns (from our scripts):
    - stem
    - box_index
    - <label_col>  (visibility or background)
    """
    if path is None or not path.exists():
        return {}
    import csv

    out: dict[tuple[str, int], str] = {}
    with path.open("r", encoding="utf-8", newline="") as f:
        r = csv.DictReader(f)
        for row in r:
            try:
                stem = str(row.get("stem") or "").strip()
                idx = int(float(str(row.get("box_index") or "0").strip()))
                lab = str(row.get(label_col) or "").strip().lower()
            except Exception:
                continue
            if not stem:
                continue
            if not lab:
                lab = "unknown"
            out[(stem, idx)] = lab
    return out


def _difficulty_percentile_thresholds(heights: np.ndarray) -> tuple[float, float, float]:
    """Returns (p20, p50, p55) for gt heights (px).

    Target distribution: Easy 45% / Moderate 35% / Hard 20%.
    """
    if heights.size == 0:
        return 0.0, 0.0, 0.0
    p20 = float(np.quantile(heights, 0.20))
    p50 = float(np.quantile(heights, 0.50))
    p55 = float(np.quantile(heights, 0.55))
    return p20, p50, p55


def _pct_rank(value: float, *, p25: float, p50: float, p75: float) -> float:
    """Map a height to a rough percentile-based score in [0,1]."""
    # Piecewise-linear using the quartiles (robust, doesn't need full distribution).
    if p75 <= 0:
        return 0.0
    if value <= p25:
        return 0.25 * (value / max(p25, 1e-9))
    if value <= p50:
        return 0.25 + 0.25 * ((value - p25) / max(p50 - p25, 1e-9))
    if value <= p75:
        return 0.50 + 0.25 * ((value - p50) / max(p75 - p50, 1e-9))
    # Above p75, saturate towards 1.0
    return 0.75 + 0.25 * min(1.0, (value - p75) / max(p75, 1e-9))


def _visibility_score(label: str) -> float:
    lab = (label or "").strip().lower()
    if lab == "good":
        return 1.0
    if lab == "medium":
        return 0.5
    if lab == "poor":
        return 0.0
    return 0.5


def _background_score(label: str) -> float:
    lab = (label or "").strip().lower()
    if lab == "water":
        return 1.0
    if lab == "mixed":
        return 0.5
    if lab == "coral":
        return 0.0
    return 0.5


def _safe_div(a: float, b: float) -> float:
    return float(a / b) if b else 0.0


def _load_image_size(image_path: Path) -> tuple[int, int]:
    from PIL import Image

    im = Image.open(image_path)
    return im.size  # (w, h)


def _yolo_xywhn_to_xyxy_px(x: float, y: float, w: float, h: float, im_w: int, im_h: int) -> tuple[float, float, float, float]:
    cx = x * im_w
    cy = y * im_h
    bw_px = w * im_w
    bh_px = h * im_h
    x1 = cx - bw_px / 2
    y1 = cy - bh_px / 2
    x2 = cx + bw_px / 2
    y2 = cy + bh_px / 2
    return x1, y1, x2, y2


def read_yolo_labels(
    label_path: Path,
    *,
    im_w: int,
    im_h: int,
    has_conf: bool,
) -> BoxSet:
    if not label_path.exists():
        empty = np.zeros((0, 4), dtype=np.float32)
        return BoxSet(xyxy=empty, cls=np.zeros((0,), dtype=np.int64), conf=(np.zeros((0,), dtype=np.float32) if has_conf else None))

    xyxy: list[list[float]] = []
    cls: list[int] = []
    conf: list[float] = []

    for line in label_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        if has_conf:
            if len(parts) < 6:
                continue
            try:
                c = int(float(parts[0]))
                x, y, w, h, cf = map(float, parts[1:6])
            except ValueError:
                continue
        else:
            if len(parts) < 5:
                continue
            try:
                c = int(float(parts[0]))
                x, y, w, h = map(float, parts[1:5])
            except ValueError:
                continue
            cf = 1.0

        x1, y1, x2, y2 = _yolo_xywhn_to_xyxy_px(x, y, w, h, im_w, im_h)
        xyxy.append([x1, y1, x2, y2])
        cls.append(c)
        if has_conf:
            conf.append(cf)

    if not xyxy:
        empty = np.zeros((0, 4), dtype=np.float32)
        return BoxSet(xyxy=empty, cls=np.zeros((0,), dtype=np.int64), conf=(np.zeros((0,), dtype=np.float32) if has_conf else None))

    xyxy_arr = np.array(xyxy, dtype=np.float32)
    cls_arr = np.array(cls, dtype=np.int64)
    if has_conf:
        conf_arr = np.array(conf, dtype=np.float32)
    else:
        conf_arr = None

    return BoxSet(xyxy=xyxy_arr, cls=cls_arr, conf=conf_arr)


def _box_iou(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    if a.size == 0 or b.size == 0:
        return np.zeros((a.shape[0], b.shape[0]), dtype=np.float32)

    ax1, ay1, ax2, ay2 = a[:, 0:1], a[:, 1:2], a[:, 2:3], a[:, 3:4]
    bx1, by1, bx2, by2 = b[:, 0], b[:, 1], b[:, 2], b[:, 3]

    xx1 = np.maximum(ax1, bx1)
    yy1 = np.maximum(ay1, by1)
    xx2 = np.minimum(ax2, bx2)
    yy2 = np.minimum(ay2, by2)

    inter_w = np.maximum(0.0, xx2 - xx1)
    inter_h = np.maximum(0.0, yy2 - yy1)
    inter = inter_w * inter_h

    a_area = np.maximum(0.0, ax2 - ax1) * np.maximum(0.0, ay2 - ay1)
    b_area = np.maximum(0.0, bx2 - bx1) * np.maximum(0.0, by2 - by1)

    union = a_area + b_area - inter + 1e-9
    return (inter / union).astype(np.float32)


def _heights_xyxy(xyxy: np.ndarray) -> np.ndarray:
    if xyxy.size == 0:
        return np.zeros((0,), dtype=np.float32)
    return (xyxy[:, 3] - xyxy[:, 1]).astype(np.float32)


def _voc_ap_11pt(precision: np.ndarray, recall: np.ndarray) -> float:
    ap = 0.0
    for t in np.linspace(0, 1, 11):
        p = precision[recall >= t].max() if np.any(recall >= t) else 0.0
        ap += float(p) / 11.0
    return float(ap)


def _voc_ap_continuous(precision: np.ndarray, recall: np.ndarray) -> float:
    if precision.size == 0:
        return 0.0
    # Append sentinel endpoints
    mrec = np.concatenate(([0.0], recall, [1.0]))
    mpre = np.concatenate(([0.0], precision, [0.0]))
    # Precision envelope
    for i in range(mpre.size - 2, -1, -1):
        mpre[i] = max(mpre[i], mpre[i + 1])
    # Area under curve
    idx = np.where(mrec[1:] != mrec[:-1])[0]
    return float(np.sum((mrec[idx + 1] - mrec[idx]) * mpre[idx + 1]))


def _evaluate_point_metrics(
    *,
    images: list[Path],
    gt_labels_dir: Path,
    pred_labels_dir: Path,
    conf_th: float,
    iou_th: float,
    min_height_px: int,
    # Optional per-box attribute filters
    gt_keep_mask_fn: "callable | None" = None,
    pr_keep_mask_fn: "callable | None" = None,
) -> tuple[PointMetrics, dict[int, PointMetrics]]:
    tp = fp = fn = 0
    per_class: dict[int, list[int]] = {}

    for image_path in images:
        im_w, im_h = _load_image_size(image_path)
        gt_path = gt_labels_dir / f"{image_path.stem}.txt"
        pr_path = pred_labels_dir / f"{image_path.stem}.txt"

        gt = read_yolo_labels(gt_path, im_w=im_w, im_h=im_h, has_conf=False)
        pr = read_yolo_labels(pr_path, im_w=im_w, im_h=im_h, has_conf=True)

        # Difficulty filter: ignore GT smaller than min height
        gt_h = _heights_xyxy(gt.xyxy)
        gt_keep = gt_h >= float(min_height_px)
        if gt_keep_mask_fn is not None and gt.xyxy.shape[0] > 0:
            try:
                extra_keep = np.asarray(gt_keep_mask_fn(image_path, gt, gt_h), dtype=bool)
                if extra_keep.shape[0] == gt_keep.shape[0]:
                    gt_keep = gt_keep & extra_keep
            except Exception:
                # never fail evaluation due to attribute sidecars
                pass
        gt_ign = ~gt_keep
        gt_xyxy = gt.xyxy[gt_keep]
        gt_cls = gt.cls[gt_keep]
        ign_xyxy = gt.xyxy[gt_ign]
        ign_cls = gt.cls[gt_ign]

        # Apply confidence threshold + ignore-small predictions (do not count as FP)
        if pr.conf is None:
            pr_conf = np.ones((pr.xyxy.shape[0],), dtype=np.float32)
        else:
            pr_conf = pr.conf
        pr_keep_conf = pr_conf >= float(conf_th)
        pr_xyxy0 = pr.xyxy[pr_keep_conf]
        pr_cls0 = pr.cls[pr_keep_conf]
        pr_conf0 = pr_conf[pr_keep_conf]

        pr_h = _heights_xyxy(pr_xyxy0)
        pr_keep_size = pr_h >= float(min_height_px)
        if pr_keep_mask_fn is not None and pr_xyxy0.shape[0] > 0:
            try:
                extra_pr_keep = np.asarray(pr_keep_mask_fn(image_path, pr, pr_h, pr_keep_conf), dtype=bool)
                # extra_pr_keep must align with pr_xyxy0 (after conf threshold)
                if extra_pr_keep.shape[0] == pr_keep_size.shape[0]:
                    pr_keep_size = pr_keep_size & extra_pr_keep
            except Exception:
                pass
        pr_xyxy = pr_xyxy0[pr_keep_size]
        pr_cls = pr_cls0[pr_keep_size]
        pr_conf1 = pr_conf0[pr_keep_size]

        # Match: greedy by confidence, class-aware
        if gt_xyxy.shape[0] == 0:
            # All predictions are FP unless they overlap an ignored GT of same class.
            if pr_xyxy.shape[0] == 0:
                continue
            if ign_xyxy.shape[0] == 0:
                fp_i = int(pr_xyxy.shape[0])
                fp += fp_i
                for c in np.unique(pr_cls):
                    arr = per_class.setdefault(int(c), [0, 0, 0])
                    arr[1] += int((pr_cls == c).sum())
                continue

            ious_ign = _box_iou(pr_xyxy, ign_xyxy)
            for pi in range(pr_xyxy.shape[0]):
                c = int(pr_cls[pi])
                cand_ign = np.where(ign_cls == c)[0]
                if cand_ign.size and float(ious_ign[pi, cand_ign].max(initial=0.0)) >= float(iou_th):
                    # ignore
                    continue
                fp += 1
                arr = per_class.setdefault(c, [0, 0, 0])
                arr[1] += 1
            continue

        if pr_xyxy.shape[0] == 0:
            fn_i = int(gt_xyxy.shape[0])
            fn += fn_i
            for c in np.unique(gt_cls):
                arr = per_class.setdefault(int(c), [0, 0, 0])
                arr[2] += int((gt_cls == c).sum())
            continue

        order = np.argsort(-pr_conf1)
        ious = _box_iou(pr_xyxy[order], gt_xyxy)
        ious_ign = _box_iou(pr_xyxy[order], ign_xyxy) if ign_xyxy.shape[0] else None
        gt_used = np.zeros((gt_xyxy.shape[0],), dtype=bool)

        for pi, p_idx in enumerate(order):
            c = int(pr_cls[p_idx])
            cand = np.where((gt_cls == c) & (~gt_used))[0]
            if cand.size == 0:
                # If it overlaps an ignored GT, do not count as FP.
                if ious_ign is not None:
                    cand_ign = np.where(ign_cls == c)[0]
                    if cand_ign.size and float(ious_ign[pi, cand_ign].max(initial=0.0)) >= float(iou_th):
                        continue

                fp += 1
                arr = per_class.setdefault(c, [0, 0, 0])
                arr[1] += 1
                continue

            best = cand[np.argmax(ious[pi, cand])]
            if float(ious[pi, best]) >= float(iou_th):
                gt_used[best] = True
                tp += 1
                arr = per_class.setdefault(c, [0, 0, 0])
                arr[0] += 1
            else:
                # If it overlaps an ignored GT, do not count as FP.
                if ious_ign is not None:
                    cand_ign = np.where(ign_cls == c)[0]
                    if cand_ign.size and float(ious_ign[pi, cand_ign].max(initial=0.0)) >= float(iou_th):
                        continue

                fp += 1
                arr = per_class.setdefault(c, [0, 0, 0])
                arr[1] += 1

        fn_i = int((~gt_used).sum())
        fn += fn_i
        for c in np.unique(gt_cls):
            c = int(c)
            missed = int(((gt_cls == c) & (~gt_used)).sum())
            if missed:
                arr = per_class.setdefault(c, [0, 0, 0])
                arr[2] += missed

    point = PointMetrics(tp=tp, fp=fp, fn=fn, precision=_safe_div(tp, tp + fp), recall=_safe_div(tp, tp + fn))
    per_class_out: dict[int, PointMetrics] = {}
    for c, (tpc, fpc, fnc) in per_class.items():
        per_class_out[int(c)] = PointMetrics(tp=int(tpc), fp=int(fpc), fn=int(fnc), precision=_safe_div(tpc, tpc + fpc), recall=_safe_div(tpc, tpc + fnc))

    return point, per_class_out


def _evaluate_pr_ap(
    *,
    images: list[Path],
    gt_labels_dir: Path,
    pred_labels_dir: Path,
    iou_th: float,
    min_height_px: int,
    num_classes: int | None,
    gt_keep_mask_fn: "callable | None" = None,
    pr_keep_mask_fn: "callable | None" = None,
) -> dict[int, ClassPrCurve]:
    # Build GT index: class -> image -> boxes + ignore flags
    gt_by_cls: dict[int, dict[str, dict[str, np.ndarray]]] = {}
    n_gt_by_cls: dict[int, int] = {}

    for image_path in images:
        im_w, im_h = _load_image_size(image_path)
        gt_path = gt_labels_dir / f"{image_path.stem}.txt"
        gt = read_yolo_labels(gt_path, im_w=im_w, im_h=im_h, has_conf=False)
        gt_h = _heights_xyxy(gt.xyxy)
        keep = gt_h >= float(min_height_px)
        if gt_keep_mask_fn is not None and gt.xyxy.shape[0] > 0:
            try:
                extra_keep = np.asarray(gt_keep_mask_fn(image_path, gt, gt_h), dtype=bool)
                if extra_keep.shape[0] == keep.shape[0]:
                    keep = keep & extra_keep
            except Exception:
                pass

        ignore = ~keep

        for c in np.unique(gt.cls):
            c = int(c)
            mask = gt.cls == c
            boxes = gt.xyxy[mask]
            ign = ignore[mask]
            if boxes.shape[0] == 0:
                continue
            cls_map = gt_by_cls.setdefault(c, {})
            cls_map[image_path.stem] = {
                "boxes": boxes,
                "ignore": ign.astype(bool),
                "used": np.zeros((boxes.shape[0],), dtype=bool),
            }
            n_gt_by_cls[c] = n_gt_by_cls.get(c, 0) + int((~ign).sum())

    # Collect detections per class
    dets_by_cls: dict[int, list[tuple[str, float, np.ndarray]]] = {}

    for image_path in images:
        im_w, im_h = _load_image_size(image_path)
        pr_path = pred_labels_dir / f"{image_path.stem}.txt"
        pr = read_yolo_labels(pr_path, im_w=im_w, im_h=im_h, has_conf=True)
        if pr.conf is None or pr.xyxy.shape[0] == 0:
            continue

        pr_h = _heights_xyxy(pr.xyxy)
        keep = pr_h >= float(min_height_px)
        if pr_keep_mask_fn is not None and pr.xyxy.shape[0] > 0:
            try:
                # Here pr_keep_mask_fn expects the full pred set (no conf threshold in PR/AP)
                extra_keep = np.asarray(pr_keep_mask_fn(image_path, pr, pr_h, None), dtype=bool)
                if extra_keep.shape[0] == keep.shape[0]:
                    keep = keep & extra_keep
            except Exception:
                pass
        pr_xyxy = pr.xyxy[keep]
        pr_cls = pr.cls[keep]
        pr_conf = pr.conf[keep]

        for i in range(pr_xyxy.shape[0]):
            c = int(pr_cls[i])
            dets_by_cls.setdefault(c, []).append((image_path.stem, float(pr_conf[i]), pr_xyxy[i].astype(np.float32)))

    # Determine which classes to evaluate
    if num_classes is not None:
        classes = list(range(int(num_classes)))
    else:
        classes = sorted(set(gt_by_cls.keys()) | set(dets_by_cls.keys()))

    curves: dict[int, ClassPrCurve] = {}

    for c in classes:
        n_gt = int(n_gt_by_cls.get(c, 0))
        dets = dets_by_cls.get(c, [])
        if n_gt == 0 and not dets:
            curves[c] = ClassPrCurve(
                cls_id=int(c),
                n_gt=0,
                ap_11=0.0,
                ap_continuous=0.0,
                scores=np.zeros((0,), dtype=np.float32),
                precision=np.zeros((0,), dtype=np.float32),
                recall=np.zeros((0,), dtype=np.float32),
            )
            continue

        dets = sorted(dets, key=lambda x: x[1], reverse=True)
        scores_all = np.array([float(s) for (_, s, _) in dets], dtype=np.float32)
        tps = np.zeros((len(dets),), dtype=np.float32)
        fps = np.zeros((len(dets),), dtype=np.float32)

        for i, (img_id, score, box) in enumerate(dets):
            gt_entry = gt_by_cls.get(c, {}).get(img_id)
            if gt_entry is None:
                # No GT of this class in this image -> FP
                fps[i] = 1.0
                continue

            gt_boxes = gt_entry["boxes"]
            gt_ignore = gt_entry["ignore"]
            gt_used = gt_entry["used"]

            ious = _box_iou(box[None, :], gt_boxes)[0]
            j = int(np.argmax(ious)) if ious.size else -1
            best_iou = float(ious[j]) if j >= 0 else 0.0

            if best_iou < float(iou_th):
                fps[i] = 1.0
                continue

            # If best match is ignored GT, ignore this detection (neither TP nor FP)
            if bool(gt_ignore[j]):
                # ignored
                continue

            if bool(gt_used[j]):
                fps[i] = 1.0
                continue

            gt_used[j] = True
            tps[i] = 1.0

        # Remove ignored detections (where tp=fp=0) from curve computation
        valid = (tps + fps) > 0
        tps2 = tps[valid]
        fps2 = fps[valid]
        scores2 = scores_all[valid]

        if tps2.size == 0:
            scores2 = np.zeros((0,), dtype=np.float32)
            precision = np.zeros((0,), dtype=np.float32)
            recall = np.zeros((0,), dtype=np.float32)
        else:
            cum_tp = np.cumsum(tps2)
            cum_fp = np.cumsum(fps2)
            precision = (cum_tp / (cum_tp + cum_fp + 1e-9)).astype(np.float32)
            recall = (cum_tp / (float(n_gt) + 1e-9)).astype(np.float32)

        ap11 = _voc_ap_11pt(precision.astype(float), recall.astype(float)) if n_gt > 0 else 0.0
        apc = _voc_ap_continuous(precision.astype(float), recall.astype(float)) if n_gt > 0 else 0.0

        curves[int(c)] = ClassPrCurve(
            cls_id=int(c),
            n_gt=int(n_gt),
            ap_11=float(ap11),
            ap_continuous=float(apc),
            scores=scores2.astype(np.float32),
            precision=precision,
            recall=recall,
        )

    return curves


def evaluate_kitti_style(
    *,
    dataset_dir: Path,
    split: str,
    pred_labels_dir: Path,
    conf_th: float,
    iou_th: float,
    difficulties: list[tuple[str, int]] | list[dict[str, object]],
    num_classes: int | None = None,
    attr_cfg: AttributeDifficultyConfig | None = None,
) -> list[DifficultyResult]:
    images_dir = dataset_dir / split / "images"
    gt_labels_dir = dataset_dir / split / "labels"

    images = sorted([p for p in images_dir.iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png"}])

    # Load attribute sidecars (best-effort)
    attr_cfg2 = (attr_cfg or AttributeDifficultyConfig()).resolve(dataset_dir=dataset_dir, split=split)
    vis_map = _try_load_attr_csv(Path(attr_cfg2.visibility_csv), label_col="visibility") if attr_cfg2.visibility_csv else {}
    bg_map = _try_load_attr_csv(Path(attr_cfg2.background_csv), label_col="background") if attr_cfg2.background_csv else {}

    # Precompute GT height distribution quartiles for size percent score
    gt_heights: list[float] = []
    for img_path in images:
        w, h = _load_image_size(img_path)
        gt_path = gt_labels_dir / f"{img_path.stem}.txt"
        gt = read_yolo_labels(gt_path, im_w=w, im_h=h, has_conf=False)
        if gt.xyxy.shape[0] == 0:
            continue
        gt_heights.extend([float(x) for x in _heights_xyxy(gt.xyxy)])
    p25, p50, p75 = _difficulty_percentile_thresholds(np.array(gt_heights, dtype=np.float32))

    out: list[DifficultyResult] = []

    # Allow a richer difficulty spec while keeping backward compatibility.
    # Spec form (dict):
    # {
    #   'name': str,
    #   'min_h': int,
    #   'type': 'size' | 'visibility' | 'background' | 'combined',
    #   'min_size_pct': float (0..1),
    #   'min_visibility_pct': float (0..1),
    #   'min_background_pct': float (0..1),
    # }
    normalized: list[dict[str, object]] = []
    if difficulties and isinstance(difficulties[0], dict):
        normalized = [dict(x) for x in difficulties]  # type: ignore[list-item]
    else:
        normalized = [{"name": str(n), "min_h": int(m), "type": "size"} for (n, m) in difficulties]  # type: ignore[arg-type]

    for spec in normalized:
        name = str(spec.get("name", "difficulty"))
        min_h = int(spec.get("min_h", spec.get("min_height_px", 1)))
        dtype = str(spec.get("type", "size")).strip().lower()

        min_size_pct = spec.get("min_size_pct")
        min_vis_pct = spec.get("min_visibility_pct")
        min_bg_pct = spec.get("min_background_pct")

        # Default thresholds (tunable later). These interpretability-friendly defaults
        # create 4 primary difficulty slices.
        if min_size_pct is None:
            # "size" means fish is not tiny; "hard size" is tiny.
            min_size_pct = 0.50 if dtype in {"size", "combined"} else 0.0
        if min_vis_pct is None:
            min_vis_pct = 0.50 if dtype in {"visibility", "combined"} else 0.0
        if min_bg_pct is None:
            min_bg_pct = 0.50 if dtype in {"background", "combined"} else 0.0

        min_size_pct_f = float(min_size_pct)
        min_vis_pct_f = float(min_vis_pct)
        min_bg_pct_f = float(min_bg_pct)

        def gt_keep(image_path: Path, gt: BoxSet, gt_h: np.ndarray) -> np.ndarray:
            keep0 = gt_h >= float(min_h)
            if gt.xyxy.shape[0] == 0:
                return keep0

            # Build a boolean keep mask by evaluating each GT box's attribute scores.
            out_keep = keep0.copy()
            stem = image_path.stem
            for i in range(int(gt.xyxy.shape[0])):
                if not out_keep[i]:
                    continue

                # size pct from height relative to dataset quartiles
                size_pct = _pct_rank(float(gt_h[i]), p25=p25, p50=p50, p75=p75)
                if size_pct < float(min_size_pct_f):
                    out_keep[i] = False
                    continue

                vis_lab = vis_map.get((stem, i), "unknown")
                if _visibility_score(vis_lab) < float(min_vis_pct_f):
                    out_keep[i] = False
                    continue

                bg_lab = bg_map.get((stem, i), "unknown")
                if _background_score(bg_lab) < float(min_bg_pct_f):
                    out_keep[i] = False
                    continue

            return out_keep

        # For predictions: we can't reliably compute these attributes unless we run
        # feature extraction on predicted boxes. For now, we keep PR/points on the
        # same geometric min-height gate only.
        # (Later we can add a pred-box attribute extractor to compare error modes.)
        def pr_keep(_image_path: Path, pr: BoxSet, pr_h: np.ndarray, _pr_keep_conf) -> np.ndarray:
            if pr.xyxy.shape[0] == 0:
                return np.zeros((0,), dtype=bool)
            return pr_h >= float(min_h)

        point, per_class = _evaluate_point_metrics(
            images=images,
            gt_labels_dir=gt_labels_dir,
            pred_labels_dir=pred_labels_dir,
            conf_th=conf_th,
            iou_th=iou_th,
            min_height_px=int(min_h),
            gt_keep_mask_fn=gt_keep,
            pr_keep_mask_fn=pr_keep,
        )

        pr_curves = _evaluate_pr_ap(
            images=images,
            gt_labels_dir=gt_labels_dir,
            pred_labels_dir=pred_labels_dir,
            iou_th=iou_th,
            min_height_px=int(min_h),
            num_classes=num_classes,
            gt_keep_mask_fn=gt_keep,
            pr_keep_mask_fn=None,
        )

        aps11 = [c.ap_11 for c in pr_curves.values() if c.n_gt > 0]
        apsc = [c.ap_continuous for c in pr_curves.values() if c.n_gt > 0]
        map11 = float(np.mean(aps11)) if aps11 else 0.0
        mapc = float(np.mean(apsc)) if apsc else 0.0

        out.append(
            DifficultyResult(
                name=str(name),
                min_height_px=int(min_h),
                iou_th=float(iou_th),
                size_pct=(min_size_pct_f if dtype in {"size", "combined"} else None),
                visibility_pct=(min_vis_pct_f if dtype in {"visibility", "combined"} else None),
                background_pct=(min_bg_pct_f if dtype in {"background", "combined"} else None),
                point=point,
                per_class=per_class,
                pr_curves=pr_curves,
                map_11=map11,
                map_continuous=mapc,
            )
        )

    return out
